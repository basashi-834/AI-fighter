/**
 * キャラクターの「ポーズ」。
 *
 * 画像を 1 枚も使わずに、その場で骨格を組んで描きます。
 * 絵を用意しなくても全キャラ・全技ぶんの動きが出せるのと、
 * 技を足したときに絵の用意を待たなくていいのが利点です。
 *
 * 角度は「真下を 0 度として、前方へ回す向きを + 」で数えます。
 *   0   = 真下              90  = 前方へ水平
 *   180 = 真上              -90 = 後方へ水平
 */

export interface Pose {
  /** 腰の位置。[前後, 高さ] */
  hip: [number, number];
  /** 胴の傾き（+ で前かがみ）。 */
  torso: number;
  /** 頭の傾き。 */
  head: number;
  /** 前側の腕 [肩, ひじ]。 */
  armF: [number, number];
  /** 奥側の腕。 */
  armB: [number, number];
  /** 前側の脚 [股, ひざ]。 */
  legF: [number, number];
  /** 奥側の脚。 */
  legB: [number, number];
  /** 全身の前後の傾き（吹き飛びなど）。 */
  lean?: number;
}

export interface AttackPose {
  /** 発生前（ためる）。 */
  wind: Pose;
  /** 当たる瞬間（伸ばす）。 */
  strike: Pose;
  /** 硬直（戻す）。 */
  rec: Pose;
}

function P(
  hip: [number, number],
  torso: number,
  head: number,
  armF: [number, number],
  armB: [number, number],
  legF: [number, number],
  legB: [number, number],
  lean = 0,
): Pose {
  return { hip, torso, head, armF, armB, legF, legB, lean };
}

